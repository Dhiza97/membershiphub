export async function downloadCertificatePdf(certificate) {
  const { jsPDF } = await import('jspdf')
  const document = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' })
  const width = document.internal.pageSize.getWidth()
  const height = document.internal.pageSize.getHeight()
  const center = width / 2

  document.setDrawColor(114, 0, 97)
  document.setLineWidth(1.2)
  document.rect(10, 10, width - 20, height - 20)
  document.setDrawColor(197, 154, 36)
  document.setLineWidth(0.35)
  document.rect(13, 13, width - 26, height - 26)
  document.setTextColor(114, 0, 97)
  document.setFont('helvetica', 'bold')
  document.setFontSize(12)
  document.text('MEMBERSHIPHUB', center, 39, { align: 'center' })
  document.setTextColor(9, 9, 9)
  document.setFontSize(24)
  document.text('CERTIFICATE OF COMPLETION', center, 57, { align: 'center' })
  document.setFont('helvetica', 'normal')
  document.setFontSize(12)
  document.text('This certifies that', center, 72, { align: 'center' })
  document.setTextColor(114, 0, 97)
  document.setFont('times', 'bold')
  document.setFontSize(27)
  const recipientLines = document.splitTextToSize(certificate.student_name, width - 60)
  document.text(recipientLines, center, 91, { align: 'center' })
  const nextLine = 91 + recipientLines.length * 11
  document.setTextColor(9, 9, 9)
  document.setFont('helvetica', 'normal')
  document.setFontSize(12)
  document.text('has successfully completed', center, nextLine + 7, { align: 'center' })
  document.setFont('helvetica', 'bold')
  document.setFontSize(16)
  document.text(document.splitTextToSize(certificate.cohort_name, width - 70), center, nextLine + 18, { align: 'center' })
  document.setFont('helvetica', 'normal')
  document.setFontSize(11)
  document.text(certificate.branch_name, center, nextLine + 27, { align: 'center' })
  document.setDrawColor(230, 226, 231)
  document.line(28, height - 29, width - 28, height - 29)
  document.setFontSize(8)
  document.text(`Certificate ${certificate.certificate_number}`, 30, height - 22)
  document.text(`Issued ${new Date(certificate.issued_at).toLocaleDateString()}`, 30, height - 17)
  document.text(`Verify at ${window.location.origin}/?verify=${certificate.verification_code}`, width - 30, height - 22, { align: 'right', maxWidth: width - 100 })
  document.save(`${certificate.certificate_number}.pdf`)
}